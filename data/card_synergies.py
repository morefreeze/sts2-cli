def _validate() -> None:
    """Validate the synergy table."""
    import os
    cards_path = "/tmp/cards_ironclad_colorless.txt"
    if os.path.exists(cards_path):
        with open(cards_path) as f:
            valid = {line.strip() for line in f if line.strip()}
        bad: list[tuple[str, str]] = []
        self_refs: list[str] = []
        asym: list[tuple[str, str]] = []
        seen = {(s, t): sc for s, lst in SYNERGIES.items() for t, sc in lst}
        for src, pairs in SYNERGIES.items():
            if src not in valid:
                bad.append(("SRC", src))
            for tgt, sc in pairs:
                if tgt not in valid:
                    bad.append((src, tgt))
                if tgt == src:
                    self_refs.append(src)
                if (tgt, src) not in seen:
                    asym.append((src, tgt))
        if bad:
            print("INVALID:", bad[:20])
        if self_refs:
            print("SELF-REF:", self_refs)
        if asym:
            print("ASYM:", asym[:20])
        if not bad and not self_refs and not asym:
            print("OK", len(SYNERGIES), "cards,",
                  sum(len(v) for v in SYNERGIES.values()), "pairs")


if __name__ == "__main__":
    _validate()
